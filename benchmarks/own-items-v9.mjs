/**
 * Suite v9 (ADR-035): more of ModelDuck's own coding and bug-fix questions,
 * including long ones. Every case is checked against a reference solution in
 * tests/reference-solutions-v9.js, and every buggy function is proven to fail
 * its own tests.
 */

const LONG_TOKENS = 1024;

function code(id, label, spec, entry, cases, { long = false } = {}) {
  return {
    id,
    label,
    category: long ? "code-long" : "code",
    prompt: `Write a JavaScript function named ${entry} that ${spec} Reply with code only.`,
    maxTokens: long ? LONG_TOKENS : 384,
    checks: [{ type: "jsTests", entry, cases }],
  };
}

function bug(id, label, buggyCode, should, entry, cases, { long = false } = {}) {
  const several = long ? "has bugs" : "has a bug";
  return {
    id,
    label,
    category: long ? "bugfix-long" : "bugfix",
    prompt:
      `This JavaScript function ${several}:\n${buggyCode}\n` +
      `It should ${should} Fix ${long ? "every bug" : "the bug"}. Reply with code only, keeping the function name ${entry}.`,
    buggyCode,
    maxTokens: long ? LONG_TOKENS : 384,
    checks: [{ type: "jsTests", entry, cases }],
  };
}

